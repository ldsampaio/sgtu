-- CreateIndex
CREATE INDEX "telemetry_events_user_id_criado_em_idx" ON "sgtu"."telemetry_events"("user_id", "criado_em");

-- AddForeignKey — condicional (donos de user_id: auth.users, saga).
DO $$
BEGIN
  IF to_regclass('auth.users') IS NOT NULL THEN
    ALTER TABLE "sgtu"."telemetry_events"
      ADD CONSTRAINT "telemetry_events_user_id_fkey" FOREIGN KEY ("user_id")
      REFERENCES "auth"."users"("id") ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
END $$;

-- Materialized view permanente do agregado diário (dashboard da onda 6 lê via
-- $queryRaw — o Prisma não modela view materializada). Sem coluna de usuário:
-- o agregado descreve O USO do sistema, nunca pessoas.
CREATE MATERIALIZED VIEW "sgtu"."vuso_diario" AS
SELECT
    ("criado_em" AT TIME ZONE 'UTC')::date AS "dia",
    "sistema",
    COUNT(*)::bigint AS "eventos",
    COUNT(DISTINCT "user_id")::bigint AS "usuarios"
FROM "sgtu"."telemetry_events"
GROUP BY 1, 2;

-- Index da view (dashboards consultam dia × sistema).
CREATE UNIQUE INDEX "vuso_diario_dia_sistema_idx" ON "sgtu"."vuso_diario"("dia", "sistema");
