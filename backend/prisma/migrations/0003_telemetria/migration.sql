-- CreateTable: eventos crus de telemetria
CREATE TABLE "sgtu"."telemetry_events" (
    "id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "user_id" UUID NOT NULL,
    "sistema" TEXT NOT NULL,
    "evento" TEXT NOT NULL,
    "rota" TEXT,
    "metadata" JSONB NOT NULL DEFAULT '{}',
    "criado_em" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "telemetry_events_pkey" PRIMARY KEY ("id")
);

-- CreateIndex (dashboard da onda 6 lê por sistema/período e por usuário)
CREATE INDEX "telemetry_events_criado_em_idx" ON "sgtu"."telemetry_events"("criado_em");

-- CreateIndex
